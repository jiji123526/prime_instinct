"""
velocity_demo.py — Prime Instinct live-odds velocity signal (proof of mechanism)

Shows that a single "last value per match" (held in memory) is enough to detect
a fast odds move in real time — no full game history needed.

Mechanism:
  1. Stream pushes a new odds value for a match.
  2. Glance at the one remembered value (the "sticky note").
  3. Compute velocity = change in implied probability / time elapsed.
  4. Fire an alarm if velocity crosses a threshold.
  5. Overwrite the remembered value with the new one.

NOTE: The threshold (0.05/sec) and the input prices here are illustrative.
The real threshold should be calibrated by backtesting against actual odds data.
The LOGIC is what this file verifies; the CALIBRATION is a separate task.
"""

from datetime import datetime

# The "sticky note" — one value per match, in memory.
# In production this would be a Redis key or a dict entry, one per live match.
last_odds = {}

# Fire when implied probability moves faster than this (prob points per second).
VELOCITY_THRESHOLD = 0.05


def implied_prob(decimal_odds):
    """Convert decimal odds to implied probability (1 / decimal_odds)."""
    return 1.0 / decimal_odds


def on_odds_update(match, price, ts_str):
    """Called each time the stream pushes a new odds value for a match."""
    ts = datetime.strptime(ts_str, "%H:%M:%S")
    new_ip = implied_prob(price)

    prev = last_odds.get(match)  # glance at the sticky note
    result = {"price": price, "ip": round(new_ip, 4), "velocity": None, "alarm": False}

    if prev is not None:
        dt = (ts - prev["ts"]).total_seconds()
        if dt > 0:
            d_ip = new_ip - prev["ip"]              # change in implied prob
            velocity = d_ip / dt                     # V = ΔIP / Δt
            result["velocity"] = round(velocity, 4)  # prob points per second
            result["alarm"] = abs(velocity) >= VELOCITY_THRESHOLD

    last_odds[match] = {"price": price, "ip": new_ip, "ts": ts}  # overwrite the note
    return result


