from datetime import datetime, timedelta

# ──────────────────────────────────────────────────────────────────────────
# Signal math (verified in test_signals.py — kept identical here)
# ──────────────────────────────────────────────────────────────────────────

def implied_prob(decimal_odds):
    return 1.0 / decimal_odds

def velocity(prev_ip, prev_ts, new_ip, new_ts):
    dt = (new_ts - prev_ts).total_seconds()
    if dt <= 0:
        return None
    return (new_ip - prev_ip) / dt

VELOCITY_THRESHOLD = 0.0015   # per-second; tuned on sample data, re-tune on real

# ──────────────────────────────────────────────────────────────────────────
