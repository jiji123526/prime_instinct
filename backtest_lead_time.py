def get_odds_timeline(game_id):
    """
    Return [(timestamp, decimal_odds_for_comeback_team), ...] through the game.
    SAMPLE DATA: Celtics' win odds drifting out, then collapsing in as Tatum's
    team mounts the late swing. Replace with The Odds API / OddsPapi historical.
    """
    base = datetime(2026, 10, 27, 22, 0, 0)  # ~game clock reference
    # (minute offset, decimal odds on the eventual winner)
    pts = [
        (0,   1.80), (15, 1.95), (30, 2.30), (45, 3.10),   # falling behind
        (60,  4.20), (66, 4.80),                            # down late — longshot
        (69,  3.40), (70, 2.10), (71, 1.40),                # sudden swing (the run)
        (72,  1.10),                                        # resolved
    ]
    return [(base + timedelta(minutes=m), odds) for m, odds in pts]

def get_social_timeline(game_id):
    """
    Return [(timestamp, social_volume), ...] — e.g. r/nba game-thread comments
    per minute. SAMPLE DATA: buzz stays flat, then spikes AFTER the moment is
    obvious. Replace with Reddit/Pushshift comment-volume pull.
    """
    base = datetime(2026, 10, 27, 22, 0, 0)
    pts = [
        (0, 40), (15, 55), (30, 60), (45, 70),
        (60, 85), (66, 95),
        (70, 110), (71, 140),
        (73, 520), (74, 900), (75, 1100),   # spike lands AFTER the swing
    ]
    return [(base + timedelta(minutes=m), v) for m, v in pts]

# ──────────────────────────────────────────────────────────────────────────
# Detection
# ──────────────────────────────────────────────────────────────────────────

def signal_fire_time(odds_timeline):
    """First timestamp where odds velocity crosses the threshold."""
    prev_ip = prev_ts = None
    for ts, odds in odds_timeline:
        ip = implied_prob(odds)
        if prev_ip is not None:
            v = velocity(prev_ip, prev_ts, ip, ts)
            if v is not None and abs(v) >= VELOCITY_THRESHOLD:
                return ts
        prev_ip, prev_ts = ip, ts
    return None

def social_spike_time(social_timeline, mult=3.0):
    """First timestamp where volume jumps to `mult`x the running baseline."""
    baseline = None
    for ts, v in social_timeline:
        if baseline is not None and baseline > 0 and v >= mult * baseline:
            return ts
        baseline = v if baseline is None else (0.7 * baseline + 0.3 * v)
    return None

def lead_time_minutes(game_id):
    odds = get_odds_timeline(game_id)
    social = get_social_timeline(game_id)
    fire = signal_fire_time(odds)
    spike = social_spike_time(social)
    if fire is None or spike is None:
        return None, fire, spike
    return (spike - fire).total_seconds() / 60.0, fire, spike

